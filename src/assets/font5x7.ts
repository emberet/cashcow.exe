/**
 * A 5x7 bitmap font, just enough to spell a ticker.
 *
 * The ASCII template needs glyph shapes, and asking a rendering library for
 * them would mean depending on whichever monospace font happens to be
 * installed -- which differs between this machine and any other, so the same
 * ticker would not render identically twice. Six hundred bytes of table makes
 * the output reproducible from the database alone, which is the property the
 * rest of the asset pipeline already has.
 *
 * Tickers are uppercase A-Z and 0-9 by the time they reach here (see
 * `sanitizeSymbol` in naming.ts); anything else falls back to UNKNOWN rather
 * than throwing, because artwork must never be the reason a launch fails.
 */

export const GLYPH_W = 5;
export const GLYPH_H = 7;

