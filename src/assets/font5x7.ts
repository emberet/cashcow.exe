export function glyph(ch: string): string[] {
  return GLYPHS[ch.toUpperCase()] ?? UNKNOWN;
}

/**
 * Lay a word out into a single grid, one blank column between glyphs.
 * Returns rows of "#" and "." so callers can decide how to paint a cell.
 */
export function banner(text: string): string[] {
  const chars = [...text];
  if (chars.length === 0) return [];

  const rows: string[] = [];
  for (let r = 0; r < GLYPH_H; r++) {
    rows.push(chars.map((c) => glyph(c)[r]).join("."));
  }
  return rows;
}
